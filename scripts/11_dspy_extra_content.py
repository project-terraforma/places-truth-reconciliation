"""
11_dspy_extra_content.py — DSPy evaluation for Hypothesis 1: extra-content classification

Purpose:
    Evaluate whether a small language model, prompted via DSPy, can correctly classify
    the semantic role of extra content in subset place-name conflicts — the specific gap
    that rules cannot fill (see README § ML Extension Hypotheses, Hypothesis 1).

    This is the primary SLM experiment for the paper. The hypothesis:
        A ChainOfThought module over a 4-class classifier, optimized with
        BootstrapFewShot, achieves ≥85% accuracy on held-out subset conflict rows
        where rule-based selection is uncertain.

Input:
    analysis/names/name_hard_cases_eval_autogenerated.csv   — 304 labeled hard cases (305 descriptor
                                                 + parenthetical, latin-script only)
    Columns used: short_name, long_name, extra_content, script_type, correct_answer

Output:
    analysis/names/dspy_h1_results.csv        — per-row predictions with correctness flag
    analysis/names/dspy_h1_summary.csv        — accuracy by class and overall

Classification taxonomy:
    business_type   Extra describes WHAT the place IS (Hotel, Supermarket, Dance Studio).
                    → Prefer longer name.
    location        Extra is a place name: city, state, country, neighborhood, street.
                    → Prefer shorter name (usually).
    disambiguation  Extra identifies a branch, owner, service list, or affiliation.
                    → Prefer shorter unless core name is non-viable alone.
    noise           Extra is listing boilerplate: credentials, legal numbers, SEO keywords,
                    marketing taglines, owner notations.
                    → Always prefer shorter name.

Usage:
    # Default: run with claude-haiku-4-5 (cheapest viable model to test first)
    python 11_dspy_extra_content.py

    # Specify a different LM:
    python 11_dspy_extra_content.py --model claude-sonnet-4-6

    # Use OpenAI:
    python 11_dspy_extra_content.py --provider openai --model gpt-4o-mini

    # Run optimizer (BootstrapFewShot) and save optimized program:
    python 11_dspy_extra_content.py --optimize --save-path optimized/h1_bootstrap.json

    # Evaluate a saved optimized program:
    python 11_dspy_extra_content.py --load-path optimized/h1_bootstrap.json

Dependencies:
    pip install dspy-ai anthropic pandas
"""

